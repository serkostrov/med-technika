import { describe, expect, it } from 'vitest'
import { splitEquipmentItems } from './header'

describe('splitEquipmentItems', () => {
  it('два пункта испытательного оборудования в одной ячейке (427-26-ЭП, ИЛ 18.11.2026)', () => {
    const line =
      'Тест пространственного разрешения рентгеновский ТПР-1-2. Зав.№ б/н. Аттестат № 3-22-ИО, ' +
      'дата выдачи 11.02.2022 г. Фантом дентальный Test Device DigiDent U, модель VD0903150. ' +
      'Зав.№10-301-0751. Аттестат № 4-22-ИО, дата выдачи 11.02.2022 г.'
    expect(splitEquipmentItems(line)).toEqual([
      'Тест пространственного разрешения рентгеновский ТПР-1-2. Зав.№ б/н. Аттестат № 3-22-ИО, дата выдачи 11.02.2022 г.',
      'Фантом дентальный Test Device DigiDent U, модель VD0903150. Зав.№10-301-0751. Аттестат № 4-22-ИО, дата выдачи 11.02.2022 г.',
    ])
  })

  it('один пункт не дробится', () => {
    const line = 'Свинцовая заглушка. Зав. № 4.'
    expect(splitEquipmentItems(line)).toEqual([line])
  })
})
